import csv
import json
import time
from pathlib import Path

import requests


BACKEND_ROOT = Path(__file__).resolve().parents[2]
PROJECT_ROOT = BACKEND_ROOT.parent

CATALOG_FILE = (
    PROJECT_ROOT
    / "datasets"
    / "metadata"
    / "evaluation"
    / "document_catalog.csv"
)

DOCUMENT_DIR = (
    PROJECT_ROOT
    / "datasets"
    / "raw"
    / "DS001_Education"
    / "benchmark_100"
)

LOG_FILE = (
    PROJECT_ROOT
    / "datasets"
    / "metadata"
    / "evaluation"
    / "document_generation_log.csv"
)

OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL_NAME = "qwen2.5:3b"

MIN_WORDS = 600
TARGET_WORDS = 800
MAX_WORDS = 1300

REQUIRED_HEADINGS = [
    "## Learning Objectives",
    "## Introduction",
    "## Core Concepts",
    "## Detailed Explanation",
    "## Example",
    "## Practical Application",
    "## Common Misconceptions",
    "## Key Takeaways",
    "## Summary",
]


SYSTEM_INSTRUCTION = """
You are creating educational benchmark material
for an accessibility-focused learning platform.

The material must be:

- factually cautious
- beginner friendly
- educational
- clear and concise
- self-contained
- free from fabricated citations
- free from external links
- free from unsupported claims
- suitable for semantic retrieval evaluation

Do not mention that the content was generated by AI.
Do not include references unless explicitly provided.
"""


def call_ollama(prompt: str) -> str:

    payload = {
        "model": MODEL_NAME,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.3,
            "top_p": 0.9,
        },
    }

    response = requests.post(
        OLLAMA_URL,
        json=payload,
        timeout=300,
    )

    response.raise_for_status()

    data = response.json()

    return data["response"].strip()


def build_prompt(document: dict) -> str:

    return f"""
{SYSTEM_INSTRUCTION}

Create one educational document.

Document metadata:

Document ID: {document["document_id"]}
Title: {document["title"]}
Domain: {document["domain"]}
Topic: {document["topic"]}
Subtopic: {document["subtopic"]}
Difficulty: {document["difficulty"]}

Target length:
Approximately {TARGET_WORDS} words.

Use EXACTLY this structure:

# {document["title"]}

## Metadata

- Document ID: {document["document_id"]}
- Domain: {document["domain"]}
- Topic: {document["topic"]}
- Subtopic: {document["subtopic"]}
- Difficulty: {document["difficulty"]}

## Learning Objectives

Write 3 to 5 clear learning objectives.

## Introduction

Introduce the concept in beginner-friendly language.

## Core Concepts

Explain the most important concepts.

## Detailed Explanation

Provide a deeper explanation using clear language.

## Example

Give at least one educational example.

## Practical Application

Explain where or how the concept is used.

## Common Misconceptions

Explain 2 to 4 common misconceptions or mistakes.

## Key Takeaways

Provide 4 to 6 concise takeaway points.

## Summary

Give a short final summary.

Important rules:

1. Do not add any extra headings.
2. Do not include external references.
3. Do not fabricate research evidence.
4. Do not mention ChatGPT, Qwen, Ollama or AI generation.
5. Keep the content within approximately
   {MIN_WORDS} to {MAX_WORDS} words.
6. Stay focused on the stated topic.
"""


def count_words(text: str) -> int:

    return len(
        text.split()
    )


def validate_document(text: str):

    errors = []

    word_count = count_words(text)

    if word_count < MIN_WORDS:
        errors.append(
            f"Too short: {word_count} words"
        )

    if word_count > MAX_WORDS:
        errors.append(
            f"Too long: {word_count} words"
        )

    for heading in REQUIRED_HEADINGS:

        if heading not in text:
            errors.append(
                f"Missing heading: {heading}"
            )

    if "TODO" in text:
        errors.append(
            "Contains TODO placeholder"
        )

    return errors


def load_catalog():

    with CATALOG_FILE.open(
        "r",
        encoding="utf-8",
        newline="",
    ) as file:

        return list(
            csv.DictReader(file)
        )


def load_log():

    if not LOG_FILE.exists():
        return {}

    with LOG_FILE.open(
        "r",
        encoding="utf-8",
        newline="",
    ) as file:

        rows = list(
            csv.DictReader(file)
        )

    return {
        row["document_id"]: row
        for row in rows
    }


def write_log(log_rows):

    fieldnames = [
        "document_id",
        "status",
        "word_count",
        "attempts",
        "message",
    ]

    with LOG_FILE.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        writer.writerows(
            log_rows.values()
        )


def main():

    print("=" * 70)
    print("A4A Learn - Benchmark Document Generator")
    print("=" * 70)

    documents = load_catalog()

    if len(documents) != 100:
        raise ValueError(
            f"Expected 100 documents, "
            f"found {len(documents)}"
        )

    DOCUMENT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    log_rows = load_log()

    completed = 0
    skipped = 0
    failed = 0

    for index, document in enumerate(
        documents,
        start=1,
    ):

        document_id = document[
            "document_id"
        ]

        output_file = (
            DOCUMENT_DIR
            / f"{document_id}.md"
        )

        print()
        print(
            f"[{index}/100] {document_id} "
            f"- {document['title']}"
        )

        existing_log = log_rows.get(
            document_id
        )

        if (
            existing_log
            and existing_log.get("status")
            == "PASS"
            and output_file.exists()
        ):

            print(
                "SKIP - already generated"
            )

            skipped += 1
            continue

        success = False
        final_text = ""
        validation_errors = []

        for attempt in range(
            1,
            4,
        ):

            print(
                f"Attempt {attempt}/3"
            )

            try:

                prompt = build_prompt(
                    document
                )

                generated_text = call_ollama(
                    prompt
                )

                validation_errors = (
                    validate_document(
                        generated_text
                    )
                )

                if not validation_errors:

                    final_text = (
                        generated_text
                    )

                    success = True
                    break

                print(
                    "Validation issues:"
                )

                for issue in validation_errors:
                    print(
                        f"  - {issue}"
                    )

            except Exception as exc:

                validation_errors = [
                    str(exc)
                ]

                print(
                    f"Generation error: {exc}"
                )

            time.sleep(1)

        if success:

            output_file.write_text(
                final_text,
                encoding="utf-8",
            )

            word_count = count_words(
                final_text
            )

            log_rows[
                document_id
            ] = {
                "document_id": document_id,
                "status": "PASS",
                "word_count": word_count,
                "attempts": attempt,
                "message": "",
            }

            completed += 1

            print(
                f"PASS - {word_count} words"
            )

        else:

            log_rows[
                document_id
            ] = {
                "document_id": document_id,
                "status": "FAIL",
                "word_count": 0,
                "attempts": 3,
                "message": " | ".join(
                    validation_errors
                ),
            }

            failed += 1

            print(
                "FAIL - document not overwritten"
            )

        # Checkpoint after every document.
        write_log(
            log_rows
        )

    print()
    print("=" * 70)
    print("GENERATION SUMMARY")
    print("=" * 70)
    print(
        f"Completed : {completed}"
    )
    print(
        f"Skipped   : {skipped}"
    )
    print(
        f"Failed    : {failed}"
    )
    print(
        f"Log       : {LOG_FILE}"
    )
    print("=" * 70)


if __name__ == "__main__":
    main()